// ─── Helper Functions ──────────────────────────────────────────────────────────

/** Search products across all fields: title, description, brand, tags, category slug, subCategory */
export function searchProducts(query: string): Product[] {
  if (!query.trim()) return ALL_PRODUCTS;
  const q = query.toLowerCase().trim();
  return ALL_PRODUCTS.filter((p) => {
    if (p.title.toLowerCase().includes(q)) return true;
    if (p.description.toLowerCase().includes(q)) return true;
    if (p.brand.toLowerCase().includes(q)) return true;
    if (p.subCategory.toLowerCase().includes(q)) return true;
    if (p.tags.some((t) => t.toLowerCase().includes(q))) return true;
    const cat = ALL_CATEGORIES.find((c) => c.id === p.category);
    if (cat?.name.toLowerCase().includes(q)) return true;
    if (cat?.slug.toLowerCase().includes(q)) return true;
    return false;
  });
}

/** Get all products for a given category slug */
export function getProductsByCategory(slug: string): Product[] {
  const cat = ALL_CATEGORIES.find((c) => c.slug === slug);
  if (!cat) return [];
  return ALL_PRODUCTS.filter((p) => p.category === cat.id);
}

/** Get products for a category slug + subCategory name */
export function getProductsBySubCategory(
  slug: string,
  subCat: string,
): Product[] {
  if (subCat === "All") return getProductsByCategory(slug);
  const cat = ALL_CATEGORIES.find((c) => c.slug === slug);
  if (!cat) return [];
  return ALL_PRODUCTS.filter(
    (p) => p.category === cat.id && p.subCategory === subCat,
  );
}

/** Top 8 products by rating for the home page bestsellers */
export function getBestSellers(limit = 8): Product[] {
  return [...ALL_PRODUCTS]
    .sort(
      (a, b) =>
        Number(b.rating) - Number(a.rating) ||
        Number(b.reviewCount) - Number(a.reviewCount),
    )
    .slice(0, limit);
}

/** Most-recently-added products (last N by id desc) for new arrivals */
export function getFeaturedProducts(limit = 8): Product[] {
  return [...ALL_PRODUCTS]
    .sort((a, b) => Number(b.id) - Number(a.id))
    .slice(0, limit);
}

/** Category lookup by slug */
export function getCategoryBySlug(slug: string): CatalogCategory | undefined {
  return ALL_CATEGORIES.find((c) => c.slug === slug);
}

/** Category name lookup by bigint id */
export function getCategoryName(id: bigint): string {
  return ALL_CATEGORIES.find((c) => c.id === id)?.name ?? "Unknown";
}
